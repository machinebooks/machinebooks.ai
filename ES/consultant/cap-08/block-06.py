PROMPT_SEÑALES_DIRECCIONAMIENTO = """Analiza el siguiente RFP
en busca de señales que sugieran direccionamiento hacia un
proveedor concreto.

Señales a buscar:
1. Requisitos de experiencia inusualmente específicos
2. Referencias a productos/tecnologías concretas sin alternativas
3. Plazos de presentación cortos para la complejidad del proyecto
4. Criterios de valoración que favorezcan un perfil muy concreto
5. Presupuesto que no alinea con el alcance (muy bajo o muy alto)
6. Requisitos que combinados solo puede cumplir un actor del mercado

IMPORTANTE: No acuses de direccionamiento — señala factores de
riesgo objetivos. Indica el nivel de riesgo (alto/medio/bajo)
y la evidencia textual con páginas.

Muchos RFPs legítimos tienen requisitos exigentes. La señal de
direccionamiento es la combinación de múltiples factores que
individualmente serían normales pero juntos resultan restrictivos."""
